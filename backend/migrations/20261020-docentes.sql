CREATE TABLE IF NOT EXISTS `docentes` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `nombres` VARCHAR(120) NOT NULL,
  `apellidos` VARCHAR(120) NOT NULL,
  `doc_pais` CHAR(2) NULL,
  `doc_tipo` ENUM('DNI') NULL,
  `doc_numero` VARCHAR(20) NULL,
  `especialidad` VARCHAR(120) NULL,
  `profesion` VARCHAR(120) NULL,
  `email` VARCHAR(254) NULL,
  `telefono` VARCHAR(30) NULL,
  `activo` TINYINT(1) NOT NULL DEFAULT 1,
  `revision` INT NOT NULL DEFAULT 1,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `docentes_documento_uq` (`doc_pais`, `doc_tipo`, `doc_numero`),
  UNIQUE KEY `docentes_email_uq` (`email`),
  KEY `docentes_nombre_idx` (`apellidos`, `nombres`),
  CONSTRAINT `docentes_nombres_chk` CHECK (CHAR_LENGTH(TRIM(`nombres`)) > 0 AND CHAR_LENGTH(TRIM(`apellidos`)) > 0),
  CONSTRAINT `docentes_texto_chk` CHECK ((`especialidad` IS NULL OR CHAR_LENGTH(TRIM(`especialidad`)) > 0) AND (`profesion` IS NULL OR CHAR_LENGTH(TRIM(`profesion`)) > 0) AND (`email` IS NULL OR CHAR_LENGTH(TRIM(`email`)) > 0) AND (`telefono` IS NULL OR CHAR_LENGTH(TRIM(`telefono`)) > 0)),
  CONSTRAINT `docentes_documento_completo_chk` CHECK ((`doc_pais` IS NULL AND `doc_tipo` IS NULL AND `doc_numero` IS NULL) OR (`doc_pais` IS NOT NULL AND `doc_tipo` IS NOT NULL AND `doc_numero` IS NOT NULL)),
  CONSTRAINT `docentes_documento_formato_chk` CHECK (`doc_tipo` IS NULL OR (`doc_pais` IS NOT NULL AND `doc_numero` IS NOT NULL AND `doc_tipo` = 'DNI' AND REGEXP_LIKE(`doc_pais`, '^PE$', 'c') AND REGEXP_LIKE(`doc_numero`, '^[0-9]{8}$', 'c') AND CHAR_LENGTH(`doc_numero`) = 8)),
  CONSTRAINT `docentes_activo_chk` CHECK (`activo` IN (0, 1)),
  CONSTRAINT `docentes_revision_chk` CHECK (`revision` >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `docente_asignaciones` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `docente_id` INT NOT NULL,
  `convocatoria_id` INT NOT NULL,
  `rol` ENUM('principal','participante') NOT NULL DEFAULT 'participante',
  `estado` ENUM('activa','retirada') NOT NULL DEFAULT 'activa',
  `principal_activo_convocatoria_id` INT GENERATED ALWAYS AS (CASE WHEN `rol` = 'principal' AND `estado` = 'activa' THEN `convocatoria_id` ELSE NULL END) STORED,
  `sustituye_a_id` INT NULL,
  `retirado_at` DATETIME(3) NULL,
  `retiro_motivo` VARCHAR(300) NULL,
  `revision` INT NOT NULL DEFAULT 1,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `docente_asignaciones_docente_edicion_uq` (`docente_id`, `convocatoria_id`),
  UNIQUE KEY `docente_asignaciones_principal_uq` (`principal_activo_convocatoria_id`),
  UNIQUE KEY `docente_asignaciones_id_edicion_uq` (`id`, `convocatoria_id`),
  KEY `docente_asignaciones_edicion_idx` (`convocatoria_id`, `estado`),
  KEY `docente_asignaciones_sustituye_idx` (`sustituye_a_id`, `convocatoria_id`),
  CONSTRAINT `docente_asignaciones_docente_fk` FOREIGN KEY (`docente_id`) REFERENCES `docentes` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `docente_asignaciones_convocatoria_fk` FOREIGN KEY (`convocatoria_id`) REFERENCES `convocatorias` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `docente_asignaciones_sustituye_fk` FOREIGN KEY (`sustituye_a_id`, `convocatoria_id`) REFERENCES `docente_asignaciones` (`id`, `convocatoria_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `docente_asignaciones_retiro_chk` CHECK ((`estado` = 'activa' AND `retirado_at` IS NULL AND `retiro_motivo` IS NULL) OR (`estado` = 'retirada' AND `retirado_at` IS NOT NULL AND `retiro_motivo` IS NOT NULL AND CHAR_LENGTH(TRIM(`retiro_motivo`)) > 0)),
  CONSTRAINT `docente_asignaciones_revision_chk` CHECK (`revision` >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

